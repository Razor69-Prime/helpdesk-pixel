'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const p=require('./report-center-products');
function row(description,category,omzet){return {transaction_description:description,product_category:category,gross_amount:omzet,hpp_amount:omzet*.5,dpp_amount:omzet*.9,ppn_amount:omzet*.1,net_amount:omzet*.4,sales_type:'BARANG'};}
const goods=[];
for(let i=1;i<=14;i++)goods.push(row('EZVIZ Model-'+i,'Camera CCTV',1500-i*20));
for(let i=1;i<=12;i++)goods.push(row('Hikvision DS-'+i,'Camera CCTV',900-i*10));
goods.push(row('EZVIZ','Camera CCTV',9999));
goods.push(row('Other Brand','Camera CCTV',9000));
goods.push(row('Penjualan Pengadaan CCTV Desa X','Camera CCTV',8000));
(async()=>{
 assert.equal(Object.keys(p.REPORTS).length,12);
 const top=p.brandModels(goods,'brand-model','',true);
 assert.equal(top.rows.length,20);
 assert.equal(top.rows.filter(x=>x.Merek==='EZVIZ').length,10);
 assert.equal(top.rows.filter(x=>x.Merek==='Hikvision').length,10);
 assert(top.rows.every(x=>x.Merek!=='Merek tidak teridentifikasi'&&x['Tipe/Model / Deskripsi']!=='Tipe tidak tercatat'));
 assert.equal(top.rows.filter(x=>x.Merek==='EZVIZ')[0]['Tipe/Model / Deskripsi'],'Model-1');
 assert(top.rows.filter(x=>x.Merek==='EZVIZ')[0]['Omzet (Rp)']>top.rows.filter(x=>x.Merek==='EZVIZ')[9]['Omzet (Rp)']);
 assert.equal(top.summary.transactions,20);
 const all=p.brandModels(goods,'brand-model');
 assert.equal(all.rows.reduce((sum,r)=>sum+r.Transaksi,0),goods.length);
 assert(top.summary.omzet<all.summary.omzet);
 assert(top.note.includes('TOP 10'));
 const deps={readRows:async()=>goods,listOutlets:async()=>[]};
 const apiTop=await p.getData({},'prod-brand-model',{},deps);
 const apiAll=await p.getData({},'prod-brand-model-all',{},deps);
 assert.equal(apiTop.rows.length,20);assert(apiTop.readOnly);
 assert(apiAll.rows.length>20);
 const selected=await p.getData({},'prod-brand-model',{brand:'EZVIZ'},deps);
 assert.equal(selected.rows.length,10);assert.equal(selected.summary.transactions,10);
 const html=fs.readFileSync('public/report-center.html','utf8');
 assert(html.includes('#report-directory{position:static;max-height:none;overflow:visible'));
 assert(html.includes('#viewer .table-wrap{max-height:none;overflow-x:auto;overflow-y:visible'));
 assert(!html.includes('max-height:58vh'));
 assert(!html.includes('max-height:calc(100vh - 118px)'));
 assert(html.includes("chosen==='prod-brand-model-all'"));
 for(const m of html.matchAll(/<script>([\s\S]*?)<\/script>/g))new vm.Script(m[1]);
 console.log('PASS PXL-RPT-0007E: independent top 10 per brand, exclude unverified models, subset KPI, full-data fallback, single vertical scroll');
})().catch(e=>{console.error(e);process.exitCode=1;});
