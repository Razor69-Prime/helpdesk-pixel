const backup=fs.readFileSync(path.join(root,'ops/backup/cloudinary-backup.js'),'utf8');
const cron=fs.readFileSync(path.join(root,'ops/backup/cloudinary-backup.cron'),'utf8');
assert(server.includes('/api/cloudinary-backup/reminder'));
assert(server.includes('/download-token'));
assert(server.includes('/download?')===false);
assert(server.includes('cloudBackupCenter.markDownloaded'));
assert(ui.includes('Cloudinary Monthly Backup'));
assert(reminder.includes('Download Backup Monthly'));
assert(index.includes('/pxl-sys-0001b-cloudinary-reminder.js'));
assert(backup.includes("args.includes('--completed')"));
assert(cron.includes('--period monthly --completed'));
