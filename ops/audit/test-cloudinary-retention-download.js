for(const p of ['2026-09','2026-10'])fs.mkdirSync(path.join(tmp,'monthly',p),{recursive:true});
assert.equal(h.reminder(tmp,'2027-03-18').active,true);
h.markDownloaded(tmp,'2026-09',{downloaded_by:'tester'});
assert.equal(h.reminder(tmp,'2027-03-18').active,false);
assert.deepEqual(h.purgeMonthly(tmp,'2027-04-01'),['2026-09']);
fs.rmSync(tmp,{recursive:true,force:true});
const server=fs.readFileSync(path.join(root,'server.js'),'utf8');
const ui=fs.readFileSync(path.join(root,'public/pxl-urg-0076-system-tools.js'),'utf8');
const reminder=fs.readFileSync(path.join(root,'public/pxl-sys-0001b-cloudinary-reminder.js'),'utf8');
