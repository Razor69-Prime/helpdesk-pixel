const assert=require('assert');
const fs=require('fs'),path=require('path'),os=require('os');
const root=path.join(__dirname,'../..');
const h=require(path.join(root,'ops/backup/cloudinary-retention-lib'));
assert.equal(h.WEEKLY_KEEP,8);
assert.equal(h.MONTHLY_RETENTION_MONTHS,6);
assert.equal(h.REMINDER_DAYS,14);
assert.equal(h.monthlyExpiry('2026-09'),'2027-04-01');
