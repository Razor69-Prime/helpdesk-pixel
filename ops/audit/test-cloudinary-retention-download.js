assert.equal(h.shouldRemind({period:'2026-09',downloaded:false},'2027-03-18'),true);
assert.equal(h.shouldPurgeMonthly({period:'2026-09',downloaded:false},'2027-04-01'),false);
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'pxl-sys-1ab-'));
for(const p of ['2026-W31','2026-W32','2026-W33','2026-W34','2026-W35','2026-W36','2026-W37','2026-W38','2026-W39'])fs.mkdirSync(path.join(tmp,'weekly',p),{recursive:true});
